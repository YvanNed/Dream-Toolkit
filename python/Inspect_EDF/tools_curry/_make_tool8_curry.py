r"""Regenerate the Curry twin of tool 8 (manual epoch rejection) from its EDF source.

Tool 8 is FORMAT-AGNOSTIC: it reads only the tool-7 `{file_id}_all-epo.fif`, the optional
`{file_id}_preprocessing_params.json` / `{file_id}_context-epo.fif` / `{file_id}_event_onsets.tsv`
companions and the optional `{file_id}_epoch_channel_rejection.tsv`, all of which the Curry tool 7
writes in the identical MNE/TSV format. There is no EDF-specific signal loading to swap (unlike
tools 6/7, whose generators replace `read_raw_edf` / suffix-dedup blocks), so this generator only:

  1. retitles the H1 markdown cell and reweords the two EDF mentions in the prose;
  2. widens the shared-library import probe so `tools/qc_rejected_epochs_lib.py` is found when Voila is
     launched from the repo root AND from `tools_curry/` (where this twin lives, the lib in `../tools`)
     -- the EDF notebook only probes `cwd` and `cwd/tools`. Same block as `8bis`.

Everything that makes the tool usable on a Curry HIGH-DENSITY montage (32-64 channels) lives in the
shared `tools/qc_rejected_epochs_lib.py` and adapts to the CHANNEL COUNT, not to the file format, so it
is inherited here unchanged: adaptive montage geometry, the `Channels` display filter, the PSD envelope,
the filtered metric table, the topomap panel (Curry keeps a real DigMontage through tool 7), the channel
triage layer, the channels x epochs flagging heatmap and the 1/f subsample/parallel levers.

Re-run this after editing `tools/8_reject_manually_voila.ipynb`:
    & "$env:LOCALAPPDATA\miniforge3\envs\inspect_edf\python.exe" tools_curry/_make_tool8_curry.py
"""
import ast
import json
from pathlib import Path

SRC = Path(__file__).resolve().parent.parent / 'tools' / '8_reject_manually_voila.ipynb'
DST = Path(__file__).resolve().parent / '8_reject_manually_curry_voila.ipynb'

nb = json.loads(SRC.read_text(encoding='utf-8'))
applied = 0


def replace_in_cell(idx, old, new, what):
    """Apply one string replacement to a cell, asserting it matched exactly once."""
    global applied
    cell = nb['cells'][idx]
    src = ''.join(cell['source'])
    assert src.count(old) == 1, f'{what}: anchor not found (or ambiguous) in cell {idx}'
    cell['source'] = src.replace(old, new).splitlines(keepends=True)
    applied += 1


# --- 1. title + prose (cell 0, markdown) ---
replace_in_cell(
    0,
    '# Tool 8: Manually reject flagged epochs (Phase 2b)',
    '# Tool 8: Manually reject flagged epochs, Curry twin (Phase 2b)\n\n'
    '*Curry twin: functionally identical to the EDF tool 8. Tool 8 reads only tool-7 `*_all-epo.fif` +\n'
    'its optional companions, which the Curry tool 7 writes in the same MNE/TSV format, so no analysis\n'
    'code differs: only the shared-library import path. The high-density support (32–64 channel\n'
    'montages) lives in the shared `tools/qc_rejected_epochs_lib.py` and adapts to the channel count.\n'
    'Generated by `tools_curry/_make_tool8_curry.py`. Do not hand-edit: edit the EDF notebook and\n'
    're-run the generator.*',
    'H1 retitle')

replace_in_cell(
    0,
    '`*_preprocessing_params.json`) from the selected *raw-epochs* folder: the raw EDF is never reloaded '
    '(EEG-only,\nwhatever channels the `.fif` holds).',
    '`*_preprocessing_params.json`) from the selected *raw-epochs* folder: the raw `.cdt` is never '
    'reloaded (EEG-only,\nwhatever channels the `.fif` holds).',
    'prose: raw EDF -> raw .cdt')

# --- 2. shared-library import probe (cell 1, code) ---
# The EDF notebook probes cwd and cwd/tools only; the twin lives in tools_curry/, so it also needs
# dirname(cwd)/tools and cwd/../tools. Canonical launch cwd stays the repo root (see SPEC 'How to run').
replace_in_cell(
    1,
    "    # Make the shared library importable whether Voila is launched from the repo root or tools/.\n"
    "    _here = os.getcwd()\n"
    "    for _cand in (_here, os.path.join(_here, 'tools')):\n"
    "        if os.path.isfile(os.path.join(_cand, 'qc_rejected_epochs_lib.py')):\n"
    "            if _cand not in sys.path:\n"
    "                sys.path.insert(0, _cand)\n"
    "            break",
    "    # Make the shared library importable whether Voila is launched from the repo root (lib in\n"
    "    # tools/) or from tools_curry/ (this twin lives there; the shared lib stays in ../tools).\n"
    "    _here = os.getcwd()\n"
    "    _lib_candidates = [_here, os.path.join(_here, 'tools'),\n"
    "                       os.path.join(os.path.dirname(_here), 'tools'),\n"
    "                       os.path.join(_here, '..', 'tools')]\n"
    "    for _cand in _lib_candidates:\n"
    "        if os.path.isfile(os.path.join(_cand, 'qc_rejected_epochs_lib.py')):\n"
    "            _cand = os.path.abspath(_cand)\n"
    "            if _cand not in sys.path:\n"
    "                sys.path.insert(0, _cand)\n"
    "            break",
    'shared-library import probe')

# --- gates: every code cell must still parse; no EDF wording may leak into the twin ---
for c in nb['cells']:
    if c['cell_type'] == 'code':
        ast.parse(''.join(c['source']))
for i, c in enumerate(nb['cells']):
    src = ''.join(c['source'])
    for bad in ('raw EDF', 'read_raw_edf', '.edf'):
        assert bad not in src, f'EDF wording {bad!r} left in cell {i}'

DST.write_text(json.dumps(nb, indent=1, ensure_ascii=False) + '\n', encoding='utf-8')
EXPECTED = 3
print(f'{applied}/{EXPECTED} replacements applied')
assert applied == EXPECTED, 'a replacement was skipped — EDF wording may have leaked into the twin'
print(f'Wrote {DST}')
